// Package applog отвечает за один-единственный вопрос: куда у
// GUI-приложения без консоли девать стандартный log.
package applog

import (
	"log"
	"os"
	"path/filepath"
)

// Open переключает стандартный log на запись в файл internal/logname
// внутри dir (создаётся, если ещё не существует) и возвращает открытый
// *os.File — вызывающий код обязан закрыть его через defer при выходе
// из main. Без этого лог улетал бы в os.Stderr, а у GUI-подсистемы
// (-H windowsgui, см. Makefile) нет консоли — то есть в никуда: то
// самое "приложение просто не открывается, и почему — не понять",
// из-за которого эта функция вообще появилась.
//
// Если открыть файл не удалось (например, dir не создать — нет прав
// на запись рядом с exe), возвращает nil и просто оставляет log
// писать в его дефолт: в GUI-режиме это по-прежнему "никуда", но так
// безопаснее, чем падать из-за невозможности вести журнал. Само это
// событие увидеть будет неоткуда, кроме статус-бара, — тем же путём,
// каким main.go сообщает обо всех остальных ошибках старта.
func Open(dir string) *os.File {
	if err := os.MkdirAll(dir, 0755); err != nil {
		return nil
	}

	f, err := os.OpenFile(filepath.Join(dir, "twixp.log"), os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		return nil
	}

	log.SetOutput(f)
	log.SetFlags(log.LstdFlags)
	return f
}
