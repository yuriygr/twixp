// +build windows

package ui

import "github.com/lxn/walk"

// pageFactory строит одну "страницу" — самодостаточный Composite со
// своим Layout/Children — внутри уже существующего, постоянно видимого
// контейнера parent. parent передаётся сюда уже реально размеченным
// (у него настоящий, ненулевой ClientBounds) — это и есть весь смысл
// pageHost, см. ниже.
type pageFactory func(parent walk.Container) (*walk.Composite, error)

// pageHost переключает "страницы" внутри одного и того же, никогда не
// скрываемого Composite. Тот же приём, что в официальном примере
// lxn/walk (examples/multiplepages/multipagemainwindow.go): каждая
// страница строится СВЕЖЕЙ уже в реально размеченный контейнер, а не
// показывается/прячется через Visible.
//
// Это не стилистика, а единственный надёжный способ в этой версии walk
// обойти целый класс багов с виджетами, которые остаются нулевого
// размера навсегда, если были невидимы в момент первого прохода
// разметки: BoxLayout.widgets() (см. vendor lxn/walk, boxlayout.go/
// container.go) исключает invisible-виджет из расчёта размеров родителя
// целиком, и последующий SetVisible(true) это не пересчитывает, если у
// виджета в итоге получаются те же Bounds, что были закэшированы (см.
// историю в mainwindow.go и signindialog.go — обе правки чинили ровно
// это, первая ценой резайз-костыля, вторая — точечно, здесь же это
// устраняется на уровне архитектуры, а не патчем на конкретный виджет).
//
// В отличие от примера lxn/walk, здесь нет ни тулбара с иконками
// страниц, ни явной концепции "текущего экшна" — переключение всегда
// программное (из кода, а не по клику пользователя на список страниц),
// так что вся эта прослойка не нужна: pageHost умеет ровно одну вещь,
// show.
type pageHost struct {
	container *walk.Composite
	current   *walk.Composite
}

// newPageHost принимает уже существующий, постоянно видимый Composite.
// pageHost не строит и не встраивает его сам — тем самым он не диктует,
// как именно контейнер вписан в общий layout окна: это решает
// вызывающий код (см. build() в mainwindow.go). Это же позволяет
// использовать pageHost не только для входа/чата, но и для будущих
// страниц настроек и т.п. — им нужен ровно тот же примитив.
func newPageHost(container *walk.Composite) *pageHost {
	return &pageHost{container: container}
}

// show строит новую страницу через build и заменяет текущую (если
// есть).
//
// Порядок сознательно ОБРАТНЫЙ по отношению к примеру lxn/walk (там
// сначала Dispose старой страницы, потом строится новая): здесь новая
// строится ПЕРВОЙ, и старая уничтожается только при успехе. Построение
// страницы может делать сетевой/файловый I/O не напрямую (сам build —
// чистая функция построения виджетов), но вызывающий код вокруг show
// обычно к этому моменту уже что-то знает о состоянии (например,
// результат входа) — и если build всё же вернёт ошибку (совсем не
// win32, а, скажем, баг в дереве виджетов), пользователь останется с
// рабочей текущей страницей, а не с пустым контейнером.
func (h *pageHost) show(build pageFactory) error {
	page, err := build(h.container)
	if err != nil {
		return err
	}

	if h.current != nil {
		old := h.current
		old.SetVisible(false)
		old.SetParent(nil)
		old.Dispose()
	}

	h.current = page

	if layout := h.container.Layout(); layout != nil {
		if err := layout.Update(false); err != nil {
			return err
		}
	}

	return nil
}
